/** Build the filtered + sorted index list for the selected file (memoized on filter state). */
function genoIndices(p) {
  const key = [p.id, geno.q, geno.chrom, geno.cls, geno.sortKey, geno.sortDir].join("|");
  if (geno.cache?.key === key) return geno.cache.idx;

  const q = geno.q.trim().toLowerCase();
  let posQuery = null;
  const m = q.match(/^(\w+)[:\s](\d+)$/);
  if (m) posQuery = { chrom: m[1].toUpperCase().replace(/^CHR/, ""), pos: m[2] };

  const idx = [];
  for (let i = 0; i < p.nSnps; i++) {
    if (geno.chrom && p.chrom[i] !== geno.chrom) continue;
    if (geno.cls && genotypeClass(p.genotype[i]) !== geno.cls) continue;
    if (q) {
      if (posQuery) {
        if (p.chrom[i].toUpperCase() !== posQuery.chrom || !String(p.pos[i]).startsWith(posQuery.pos)) continue;
      } else if (!p.rsid[i].toLowerCase().includes(q) && !String(p.pos[i]).startsWith(q) && p.genotype[i].toLowerCase() !== q) continue;
    }
    idx.push(i);
  }

  const k = geno.sortKey, d = geno.sortDir;
  if (k !== "idx" || d !== 1) {
    const cmp = {
      idx: (a, b) => a - b,
      rsid: (a, b) => p.rsid[a].localeCompare(p.rsid[b], undefined, { numeric: true }),
      chrom: (a, b) => chromIndex(p.chrom[a]) - chromIndex(p.chrom[b]) || p.pos[a] - p.pos[b],
      pos: (a, b) => p.pos[a] - p.pos[b],
      genotype: (a, b) => p.genotype[a].localeCompare(p.genotype[b]),
      cls: (a, b) => genotypeClass(p.genotype[a]).localeCompare(genotypeClass(p.genotype[b])),
    }[k];
    idx.sort((a, b) => cmp(a, b) * d);
  }
  geno.cache = { key, idx };
  return idx;
}

