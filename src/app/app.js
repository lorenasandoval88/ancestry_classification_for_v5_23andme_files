// Synthetic fallback (used only if the bundled demo cannot be fetched).
function makeDemoFile(seed = 7) {
  let s = seed;
  const rnd = () => (s = (s * 1664525 + 1013904223) >>> 0) / 2 ** 32;
  const bases = "ACGT";
  const lines = [
    "# This data file generated by 23andMe at: Mon Oct 27 12:00:00 2026",
    "# This is a synthetic demo file for the Ancestry23 UI. Positions are random.",
    "# Chip version: v5 (synthetic; ~9,700 markers instead of ~630,000)",
    "# We are using reference human assembly build 37 (also known as Annotation Release 104).",
    "# rsid\tchromosome\tposition\tgenotype",
  ];
  const perChrom = { 1: 820, 2: 780, 3: 650, 4: 600, 5: 580, 6: 640, 7: 520, 8: 480, 9: 420, 10: 450, 11: 460, 12: 440, 13: 320, 14: 300, 15: 290, 16: 310, 17: 300, 18: 270, 19: 240, 20: 230, 21: 140, 22: 150, X: 260, Y: 40, MT: 30 };
  let idx = 1;
  for (const [c, count] of Object.entries(perChrom)) {
    let p = 10_000 + Math.floor(rnd() * 500_000);
    for (let i = 0; i < count; i++) {
      p += 1_000 + Math.floor(rnd() * 400_000);
      const a = bases[Math.floor(rnd() * 4)];
      let b = bases[Math.floor(rnd() * 4)];
      const r = rnd();
      let gt;
      if (c === "Y" || c === "MT") gt = r < 0.1 ? "--" : a;
      else if (r < 0.025) gt = "--";
      else if (r < 0.035) gt = rnd() < 0.5 ? "II" : "DD";
      else if (r < 0.42) gt = a + (b === a ? bases[(bases.indexOf(a) + 1) % 4] : b);
      else gt = a + a;
      const id = rnd() < 0.96 ? `rs${Math.floor(rnd() * 2e8)}` : `i${Math.floor(rnd() * 7e6)}`;
      lines.push(`${id}\t${c}\t${p}\t${gt}`);
      idx++;
    }
  }
  return lines.join("\n");
}

