/** Parse a file and attach app-level fields (id, editable label, ancestry slot). */
function parseForApp(text, fileName) {
  return Object.assign(parse23andMe(text, fileName), { id: nextId++, label: defaultLabel(fileName), ancestry: null });
}

function defaultLabel(fileName) {
  const m = fileName.match(/^genome_(.+?)(_v\d|_Full)/i);
  return m ? m[1].replace(/_/g, " ") : fileName.replace(/\.[^.]+$/, "");
}

