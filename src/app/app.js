const $ = (sel, root = document) => root.querySelector(sel);
const fmt = new Intl.NumberFormat("en-US");
const pct = (x, d = 2) => `${(x * 100).toFixed(d)}%`;
const esc = (s) => String(s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
const debounce = (fn, ms = 150) => { let t; return (...a) => { clearTimeout(t); t = setTimeout(() => fn(...a), ms); }; };
const highlight = (text, q) => {
  if (!q) return esc(text);
  const i = String(text).toLowerCase().indexOf(q.toLowerCase());
  if (i === -1) return esc(text);
  const s = String(text);
  return `${esc(s.slice(0, i))}<mark>${esc(s.slice(i, i + q.length))}</mark>${esc(s.slice(i + q.length))}`;
};
function downloadCsv(name, headers, rows) {
  const q = (v) => { const s = String(v ?? ""); return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s; };
  const csv = [headers.join(","), ...rows.map((r) => r.map(q).join(","))].join("\n");
  const url = URL.createObjectURL(new Blob([csv], { type: "text/csv" }));
  const a = Object.assign(document.createElement("a"), { href: url, download: name });
  a.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
function fmtBytes(b) {
  if (b < 1024) return `${b} B`;
  if (b < 1024 ** 2) return `${(b / 1024).toFixed(0)} KB`;
  return `${(b / 1024 ** 2).toFixed(1)} MB`;
}
function pushStatus(kind, html) {
  const box = $("#uploadStatus");
  const el = document.createElement("div");
  el.className = `status-line ${kind}`;
  const icon = kind === "ok" ? "fa-circle-check" : kind === "warn" ? "fa-triangle-exclamation" : kind === "err" ? "fa-circle-xmark" : "fa-circle-info";
  el.innerHTML = `<i class="fa-solid ${icon}"></i><span>${html}</span>`;
  box.prepend(el);
  while (box.children.length > 6) box.lastChild.remove();
}

