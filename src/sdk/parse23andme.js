// 23andMe raw-data parser and file-level inference (chip, build, sex).
// Pure functions, no DOM: shared by the web app and the SDK.

export const CHROM_ORDER = [...Array.from({ length: 22 }, (_, i) => String(i + 1)), "X", "Y", "MT"];

/**
 * Parse a 23andMe raw-data export.
 * Format: '#' comment lines, then tab-separated `rsid  chromosome  position  genotype`.
 * Returns column arrays (rsid, chrom, pos, genotype) plus header-derived metadata.
 */
export function parse23andMe(text, fileName = "") {
  const rsid = [], chrom = [], pos = [], genotype = [];
  const header = [];
  let generated = null, build = null, headerChip = null;

  let start = 0;
  const n = text.length;
  while (start < n) {
    let end = text.indexOf("\n", start);
    if (end === -1) end = n;
    let line = text.slice(start, end);
    start = end + 1;
    if (line.endsWith("\r")) line = line.slice(0, -1);
    if (!line) continue;

    if (line.charCodeAt(0) === 35 /* # */) {
      header.push(line);
      const m = line.match(/generated by 23andMe at:\s*(.+)$/i) || line.match(/^#\s*timestamp:\s*(.+)$/i);
      if (m) generated = m[1].trim();
      const b = line.match(/build\s*(\d{2})/i);
      if (b) build = `GRCh${b[1]}`;
      const c = line.match(/\b(v[2-5])\b/i);
      if (c && /chip|version/i.test(line)) headerChip = c[1].toLowerCase();
      continue;
    }
    if (/^rsid\t/i.test(line)) continue;

    const t1 = line.indexOf("\t");
    if (t1 === -1) continue;
    const t2 = line.indexOf("\t", t1 + 1);
    const t3 = line.indexOf("\t", t2 + 1);
    if (t2 === -1 || t3 === -1) continue;

    rsid.push(line.slice(0, t1));
    chrom.push(line.slice(t1 + 1, t2));
    pos.push(Number(line.slice(t2 + 1, t3)));
    genotype.push(line.slice(t3 + 1).trim());
  }

  if (rsid.length === 0) throw new Error("No genotype rows found. Is this a 23andMe raw-data export?");

  const stats = summarize(chrom, genotype);
  return {
    fileName,
    header,
    generated,
    build: build || "Unknown",
    chip: headerChip || inferChip(rsid.length),
    sex: inferSex(stats),
    rsid, chrom, pos, genotype,
    nSnps: rsid.length,
    nNoCall: stats.noCall,
    callRate: 1 - stats.noCall / rsid.length,
    chroms: stats.chroms,
    nChrom: stats.chroms.length,
    sizeBytes: text.length,
  };
}

export function summarize(chrom, genotype) {
  let noCall = 0, yCalled = 0, yTotal = 0, xHet = 0, xCalled = 0;
  const chromSet = new Set();
  for (let i = 0; i < chrom.length; i++) {
    const c = chrom[i], g = genotype[i];
    chromSet.add(c);
    const cls = genotypeClass(g);
    if (cls === "nocall") noCall++;
    if (c === "Y") { yTotal++; if (cls !== "nocall") yCalled++; }
    else if (c === "X") { if (cls !== "nocall") xCalled++; if (cls === "het") xHet++; }
  }
  const chroms = [...chromSet].sort((a, b) => chromIndex(a) - chromIndex(b));
  return { noCall, yCalled, yTotal, xHet, xCalled, chroms };
}

export function genotypeClass(g) {
  if (!g || g === "--" || g === "00" || g === "0") return "nocall";
  if (/[ID]/.test(g)) return "indel";
  if (g.length === 1) return "hemi";
  return g[0] === g[1] ? "hom" : "het";
}

/** Approximate chip version from marker count when the header does not state it. */
export function inferChip(nSnps) {
  if (nSnps >= 900_000) return "v3";
  if (nSnps >= 615_000) return "v5";
  if (nSnps >= 560_000) return "v4";
  if (nSnps >= 500_000) return "v2";
  return "unknown";
}

export function inferSex({ yCalled, yTotal, xHet, xCalled }) {
  if (yTotal === 0 && xCalled === 0) return "Unknown";
  const yRate = yTotal ? yCalled / yTotal : 0;
  const xHetRate = xCalled ? xHet / xCalled : 0;
  if (yRate > 0.5 || (yTotal === 0 && xHetRate < 0.02)) return "Male";
  if (yRate < 0.15 && xHetRate > 0.05) return "Female";
  return "Unknown";
}

export function chromIndex(c) {
  const i = CHROM_ORDER.indexOf(String(c));
  return i === -1 ? 999 : i;
}
