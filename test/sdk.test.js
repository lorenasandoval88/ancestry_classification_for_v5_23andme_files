import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createClassifier, parse23andMe, fromDiseasome, attachAncestry } from '../src/index.js';

function fixture() {
  const model = {
    schemaVersion: 1, modelVersion: 'synthetic-test-only', chip: 'v5', build: 'GRCh37',
    markerCount: 2,
    markers: [
      { id: 'rs1', chromosome: '1', position: 100, otherAllele: 'A', effectAllele: 'G' },
      { id: 'rs2', chromosome: '2', position: 200, otherAllele: 'C', effectAllele: 'T' }
    ],
    imputerMeans: [1, 0.5], scalerMean: [0.5, 0.5], scalerScale: [2, 1],
    pcaMean: [0.25, 0], pcaComponents: [[1, 1], ...Array.from({ length: 9 }, () => [0, 0])],
    pcaScale: [2, ...Array(9).fill(1)],
    classes: ['SAS', 'AFR', 'EUR', 'EAS', 'AMR'],
    coefficients: [[1, ...Array(9).fill(0)], ...Array.from({ length: 4 }, () => Array(10).fill(0))],
    intercepts: [0, 0, 0, 0, 0], probabilityMode: 'softmax',
    quality: { minMatchRate: 0.5, minCallRate: 0.5 }
  };
  const upload = { format: '23andMe', chip: 'v5', build: 'GRCh37', records: [
    { id: 'rs2', chromosome: 'chr2', position: 200, genotype: '--' },
    { id: 'rs1', chromosome: '1', position: 100, genotype: 'GG' }
  ] };
  return { model, upload };
}

test('reorders markers, counts effect alleles, imputes, scales, centers and whitens PCA', () => {
  const { model, upload } = fixture();
  const result = createClassifier(model).classify(upload);
  assert.equal(result.status, 'classified');
  // rs1: ((2 - .5) / 2 - .25) / 2 = .25; rs2 imputed to its mean.
  assert.ok(Math.abs(result.scores.SAS - Math.exp(0.25) / (Math.exp(0.25) + 4)) < 1e-14);
  assert.equal(result.predictedGroup, 'SAS');
  assert.equal(result.quality.imputedMarkers, 1);
  assert.equal(result.quality.callRate, 0.5);
  assert.ok(Math.abs(Object.values(result.scores).reduce((a, b) => a + b) - 1) < 1e-14);
});

test('absent markers use saved means, not batch-derived values', () => {
  const { model, upload } = fixture();
  const classifier = createClassifier(model);
  const expected = classifier.classify(upload);
  upload.records.shift();
  const actual = classifier.classify(upload);
  assert.deepEqual(actual.scores, expected.scores);
  assert.equal(actual.quality.absentMarkers, 1);
});

test('artifact mutation cannot alter a classifier', () => {
  const { model, upload } = fixture();
  const classifier = createClassifier(model);
  model.intercepts[0] = -100;
  assert.equal(classifier.classify(upload).predictedGroup, 'SAS');
});

test('raw text and canonical JSON produce the same scores', () => {
  const { model, upload } = fixture();
  const text = '# This data file generated by 23andMe\n# chip: v5\n# reference human assembly build 37 (GRCh37)\n' +
    '# rsid chromosome position genotype\nrs2\t2\t200\t--\nrs1\t1\t100\tGG\n';
  const classifier = createClassifier(model);
  assert.deepEqual(classifier.classify(text), classifier.classify(JSON.stringify(upload)));
  assert.equal(parse23andMe(text).build, 'GRCh37');
});

test('does not infer chip from record count; accepts explicitly confirmed metadata', () => {
  const { model } = fixture();
  const classifier = createClassifier(model);
  const text = '# 23andMe\n# build 37\nrs1 1 100 GG\n';
  assert.equal(classifier.classify(text).reason.code, 'UNSUPPORTED_FILE');
  assert.equal(classifier.classify(text, { chip: 'v5' }).status, 'classified');
  assert.equal(classifier.classify(text, { chip: 'v5', build: 'GRCh38' }).reason.code, 'INVALID_FILE');
});

test('accepts Diseasome parsed JSON, resolves column order, ignores appended row indices', () => {
  const { model, upload } = fixture();
  const parsed = {
    cols: ['genotype', 'rsid', 'position', 'chromosome'],
    dt: [['--', 'rs2', 200, '2', 0], ['GG', 'rs1', 100, '1', 1]],
    meta: '# This data file generated by 23andMe\n# build 37'
  };
  const classifier = createClassifier(model);
  assert.deepEqual(classifier.classify(JSON.stringify(parsed), { chip: 'v5' }),
    classifier.classify(upload));
  assert.equal(fromDiseasome(parsed, { chip: 'v5' }).format, '23andMe');
  parsed.cols[1] = 'genotype';
  assert.equal(classifier.classify(parsed).reason.code, 'INVALID_FILE');
});

test('rejects malformed or unconfirmed Diseasome uploads', () => {
  const { model } = fixture();
  const classifier = createClassifier(model);
  const parsed = { cols: ['rsid', 'chromosome', 'position', 'genotype'],
    dt: [['rs1', '1', 100, 'GG', 0]], meta: '' };
  assert.equal(classifier.classify(parsed, { chip: 'v5', build: 'GRCh37' }).reason.code, 'INVALID_FILE');
  const metadata = { format: '23andMe', chip: 'v5', build: 'GRCh37' };
  assert.equal(classifier.classify(parsed, metadata).status, 'classified');
  parsed.dt = [['rs1']];
  assert.equal(classifier.classify(parsed, metadata).reason.code, 'INVALID_FILE');
});

test('raw input needs a vendor header or an explicit provenance assertion', () => {
  const { model } = fixture();
  const classifier = createClassifier(model);
  const text = '# chip: v5\n# GRCh37\nrs1 1 100 GG\n';
  assert.equal(classifier.classify(text).reason.code, 'INVALID_FILE');
  assert.equal(classifier.classify(text, { format: '23andMe' }).status, 'classified');
  assert.equal(classifier.classify('# 23andMe\n# build 37 GRCh38\n').reason.code, 'INVALID_FILE');
});

for (const [label, change, reason] of [
  ['wrong chip', x => { x.chip = 'v4'; }, 'UNSUPPORTED_FILE'],
  ['wrong build', x => { x.build = 'GRCh38'; }, 'UNSUPPORTED_FILE'],
  ['wrong provider', x => { x.format = 'AncestryDNA'; }, 'UNSUPPORTED_FILE'],
  ['duplicate SNP', x => { x.records.push(x.records[0]); }, 'DUPLICATE_MARKER'],
  ['wrong coordinate', x => { x.records[0].position++; }, 'MARKER_MISMATCH'],
  ['wrong chromosome', x => { x.records[0].chromosome = '1'; }, 'MARKER_MISMATCH'],
  ['unexpected allele', x => { x.records[0].genotype = 'AA'; }, 'MARKER_MISMATCH'],
  ['haploid call', x => { x.records[0].genotype = 'T'; }, 'MARKER_MISMATCH'],
  ['no calls', x => { x.records[1].genotype = '--'; }, 'LOW_QUALITY'],
  ['no overlap', x => { x.records = [{ id: 'rs9' }]; }, 'LOW_QUALITY'],
  ['empty records', x => { x.records = []; }, 'INVALID_FILE'],
  ['invalid record', x => { x.records.push(null); }, 'INVALID_FILE']
]) {
  test(`rejects ${label} without prediction or scores`, () => {
    const { model, upload } = fixture();
    change(upload);
    const result = createClassifier(model).classify(upload);
    assert.equal(result.status, 'rejected');
    assert.equal(result.reason.code, reason);
    assert.ok(!('scores' in result));
    assert.ok(!('predictedGroup' in result));
  });
}

test('invalid input and conflicting headers fail closed', () => {
  const { model } = fixture();
  const classifier = createClassifier(model);
  for (const input of ['{', null, [], '# build 37\n# build 38\nrs1 1 100 GG', 'rs1 1 GG']) {
    assert.equal(classifier.classify(input).reason.code, 'INVALID_FILE');
  }
});

test('model validation rejects incompatible or unsafe artifacts', () => {
  for (const change of [
    m => { m.schemaVersion = 2; },
    m => { m.markerCount = 335632; },
    m => { m.markers[1].id = 'rs1'; },
    m => { m.scalerScale[0] = 0; },
    m => { m.imputerMeans[0] = NaN; },
    m => { m.pcaComponents.pop(); },
    m => { m.classes[0] = '__proto__'; },
    m => { m.quality.minCallRate = 0; }
  ]) {
    const { model } = fixture();
    change(model);
    assert.throws(() => createClassifier(model), TypeError);
  }
});

test('OVR scores agree with normalized sigmoid and are stable for extreme logits', () => {
  const { model, upload } = fixture();
  model.probabilityMode = 'ovr';
  let result = createClassifier(model).classify(upload);
  const sigmoid = 1 / (1 + Math.exp(-0.25));
  assert.ok(Math.abs(result.scores.SAS - sigmoid / (sigmoid + 2)) < 1e-14);
  model.intercepts.fill(-10000);
  result = createClassifier(model).classify(upload);
  assert.equal(result.status, 'classified');
  assert.ok(Object.values(result.scores).every(Number.isFinite));
});

test('attaches both successes and rejections without modifying existing profile fields', () => {
  const { model, upload } = fixture();
  const data = { profile: { example: true }, existing: 42 };
  for (const input of [upload, null]) {
    const result = createClassifier(model).classify(input);
    const attached = attachAncestry(data, result);
    assert.equal(attached.existing, 42);
    assert.equal(attached.profile, data.profile);
    assert.equal(attached.ancestry, result);
    assert.ok(!('ancestry' in data));
    assert.ok(!('records' in attached.ancestry));
  }
});
